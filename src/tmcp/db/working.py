"""Writable PostgreSQL adapter for the working dataset and the change requests (OP-01).

Each write is a change request. A second agent with the role ``approver`` must approve it (four-eyes rule).
The server applies the change in the same transaction as the approval, and it detects conflicts.
"""

import asyncio
import json
import re
import sqlite3
import time
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

import asyncpg
from ulid import ULID

from tmcp.db.base import QueryResult
from tmcp.db.catalog import REFERENCE_VIEW_SQL
from tmcp.errors import AppError, ErrorCode
from tmcp.observability import metrics
from tmcp.observability.logging import get_logger

log = get_logger(__name__)

WRITABLE_COLUMNS: tuple[str, ...] = (
    "survived",
    "pclass",
    "sex",
    "age",
    "sibsp",
    "parch",
    "fare",
    "embarked",
    "deck",
    "who",
    "adult_male",
    "alone",
)

_SCHEMA_LOCK_ID = 7_316_002  # pg_advisory_lock key: only one replica runs the bootstrap at a time

SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS passengers (
    passenger_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    survived     SMALLINT NOT NULL CHECK (survived IN (0, 1)),
    pclass       SMALLINT NOT NULL CHECK (pclass IN (1, 2, 3)),
    class        TEXT GENERATED ALWAYS AS (
                    CASE pclass WHEN 1 THEN 'First' WHEN 2 THEN 'Second' ELSE 'Third' END) STORED,
    sex          TEXT NOT NULL CHECK (sex IN ('female', 'male')),
    age          DOUBLE PRECISION CHECK (age IS NULL OR (age >= 0 AND age < 120)),
    sibsp        SMALLINT NOT NULL CHECK (sibsp >= 0),
    parch        SMALLINT NOT NULL CHECK (parch >= 0),
    fare         DOUBLE PRECISION CHECK (fare IS NULL OR fare >= 0),
    embarked     TEXT CHECK (embarked IN ('C', 'Q', 'S')),
    embark_town  TEXT GENERATED ALWAYS AS (
                    CASE embarked WHEN 'C' THEN 'Cherbourg' WHEN 'Q' THEN 'Queenstown'
                                  WHEN 'S' THEN 'Southampton' END) STORED,
    deck         TEXT CHECK (deck IN ('A', 'B', 'C', 'D', 'E', 'F', 'G')),
    who          TEXT NOT NULL CHECK (who IN ('child', 'man', 'woman')),
    adult_male   SMALLINT NOT NULL CHECK (adult_male IN (0, 1)),
    alone        SMALLINT NOT NULL CHECK (alone IN (0, 1)),
    alive        TEXT GENERATED ALWAYS AS (CASE survived WHEN 1 THEN 'yes' ELSE 'no' END) STORED
);

CREATE TABLE IF NOT EXISTS change_requests (
    id             TEXT PRIMARY KEY,
    operation      TEXT NOT NULL CHECK (operation IN ('insert', 'update', 'delete')),
    passenger_id   BIGINT,
    payload        JSONB NOT NULL DEFAULT '{}'::jsonb,
    before         JSONB,
    reason         TEXT NOT NULL,
    status         TEXT NOT NULL CHECK (status IN ('pending', 'applied', 'rejected', 'conflict', 'expired')),
    requested_by   TEXT NOT NULL,
    requested_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_by    TEXT,
    reviewed_at    TIMESTAMPTZ,
    review_comment TEXT,
    result         JSONB
);
CREATE INDEX IF NOT EXISTS change_requests_status_idx ON change_requests (status, requested_at);
"""

_PLACEHOLDER = re.compile(r"%\((p\d+)\)s")


def to_asyncpg(sql: str, params: dict[str, Any]) -> tuple[str, list[Any]]:
    """Convert sqlglot postgres placeholders ``%(p0)s`` to asyncpg positional ``$1`` parameters."""
    order: list[str] = []

    def _replace(match: re.Match[str]) -> str:
        name = match.group(1)
        if name not in order:
            order.append(name)
        return f"${order.index(name) + 1}"

    converted = _PLACEHOLDER.sub(_replace, sql)
    return converted, [params[name] for name in order]


def _iso(value: Any) -> Any:
    return value.isoformat() if isinstance(value, datetime) else value


class WorkingDatabase:
    dialect = "postgres"

    def __init__(self, dsn: str, *, pool_size: int, ttl_hours: int) -> None:
        self._dsn = dsn
        self._pool_size = pool_size
        self._ttl = timedelta(hours=ttl_hours)
        self._pool: asyncpg.Pool | None = None

    @staticmethod
    async def _init_connection(conn: asyncpg.Connection) -> None:
        await conn.set_type_codec("jsonb", encoder=json.dumps, decoder=json.loads, schema="pg_catalog")

    async def connect(self, *, attempts: int = 30, delay_s: float = 2.0) -> None:
        last_error: Exception | None = None
        for attempt in range(1, attempts + 1):
            try:
                self._pool = await asyncpg.create_pool(
                    self._dsn, min_size=1, max_size=self._pool_size, init=self._init_connection, command_timeout=30
                )
                return
            except (OSError, asyncpg.PostgresError) as exc:
                last_error = exc
                log.warning("working_db_connect_retry", attempt=attempt, error=type(exc).__name__)
                await asyncio.sleep(delay_s)
        raise RuntimeError("The working database is not available") from last_error

    async def close(self) -> None:
        if self._pool:
            await self._pool.close()

    @property
    def pool(self) -> asyncpg.Pool:
        if self._pool is None:
            raise AppError(ErrorCode.DATABASE_UNAVAILABLE, "The working database is not connected.")
        return self._pool

    async def bootstrap(self, reference_db: Path) -> int:
        """Create the schema and copy the reference rows if the table is empty. Safe with many replicas."""
        async with self.pool.acquire() as conn:
            await conn.execute("SELECT pg_advisory_lock($1)", _SCHEMA_LOCK_ID)
            try:
                await conn.execute(SCHEMA_SQL)
                count: int = await conn.fetchval("SELECT count(*) FROM passengers")
                if count == 0:
                    rows = _read_reference_rows(reference_db)
                    columns = ["passenger_id", *WRITABLE_COLUMNS]
                    await conn.copy_records_to_table("passengers", records=rows, columns=columns)
                    await conn.execute(
                        "SELECT setval(pg_get_serial_sequence('passengers', 'passenger_id'), "
                        "(SELECT max(passenger_id) FROM passengers))"
                    )
                    log.info("working_db_seeded", rows=len(rows))
                    return len(rows)
                return count
            finally:
                await conn.execute("SELECT pg_advisory_unlock($1)", _SCHEMA_LOCK_ID)

    async def check(self) -> None:
        async with self.pool.acquire() as conn:
            await conn.fetchval("SELECT 1")

    async def fetch(self, sql: str, params: dict[str, Any], *, max_rows: int, timeout_s: float) -> QueryResult:
        query, args = to_asyncpg(sql, params)
        start = time.perf_counter()
        try:
            async with self.pool.acquire() as conn, conn.transaction(readonly=True):
                await conn.execute(f"SET LOCAL statement_timeout = {int(timeout_s * 1000)}")
                stmt = await conn.prepare(query)
                columns = [a.name for a in stmt.get_attributes()]
                records = await stmt.fetch(*args)
        except asyncpg.QueryCanceledError as exc:
            raise AppError(ErrorCode.QUERY_TIMEOUT, f"The query used more than {timeout_s:g} s.") from exc
        except (OSError, asyncpg.InterfaceError) as exc:
            raise AppError(ErrorCode.DATABASE_UNAVAILABLE, "The working database is not available.") from exc
        finally:
            metrics.QUERY_DURATION.labels("working").observe(time.perf_counter() - start)
        rows = [[_to_json_number(v) for v in r.values()] for r in records[: max_rows + 1]]
        return QueryResult(columns, rows[:max_rows], len(rows) > max_rows)

    # ----- change requests -------------------------------------------------------------------------

    async def _expire_old(self, conn: asyncpg.Connection) -> None:
        expired = await conn.fetch(
            "UPDATE change_requests SET status = 'expired' WHERE status = 'pending' AND requested_at < $1 RETURNING id",
            datetime.now(UTC) - self._ttl,
        )
        if expired:
            metrics.CHANGE_REQUESTS.labels("expired").inc(len(expired))

    async def _current_row(self, conn: asyncpg.Connection, passenger_id: int, *, lock: bool) -> dict[str, Any] | None:
        # Column names come only from the constant WRITABLE_COLUMNS; the value is a bound parameter.
        sql = f"SELECT {', '.join(WRITABLE_COLUMNS)} FROM passengers WHERE passenger_id = $1"  # nosec B608
        record = await conn.fetchrow(sql + (" FOR UPDATE" if lock else ""), passenger_id)
        return dict(record) if record else None

    async def create_change_request(
        self,
        *,
        operation: str,
        passenger_id: int | None,
        payload: dict[str, Any],
        reason: str,
        requested_by: str,
    ) -> dict[str, Any]:
        async with self.pool.acquire() as conn, conn.transaction():
            before = None
            if passenger_id is not None:
                before = await self._current_row(conn, passenger_id, lock=False)
                if before is None:
                    raise AppError(ErrorCode.NOT_FOUND, f"Passenger {passenger_id} does not exist in the working data.")
            record = await conn.fetchrow(
                "INSERT INTO change_requests (id, operation, passenger_id, payload, before, reason, status, "
                "requested_by) VALUES ($1, $2, $3, $4, $5, $6, 'pending', $7) RETURNING *",
                str(ULID()),
                operation,
                passenger_id,
                payload,
                before,
                reason,
                requested_by,
            )
        metrics.CHANGE_REQUESTS.labels("pending").inc()
        return _cr_dict(record)

    async def get_change_request(self, cr_id: str) -> dict[str, Any]:
        async with self.pool.acquire() as conn:
            await self._expire_old(conn)
            record = await conn.fetchrow("SELECT * FROM change_requests WHERE id = $1", cr_id)
        if record is None:
            raise AppError(ErrorCode.NOT_FOUND, f"Change request {cr_id} does not exist.")
        return _cr_dict(record)

    async def list_change_requests(
        self, *, status: str | None, requested_by: str | None, limit: int
    ) -> list[dict[str, Any]]:
        async with self.pool.acquire() as conn:
            await self._expire_old(conn)
            records = await conn.fetch(
                "SELECT * FROM change_requests WHERE ($1::text IS NULL OR status = $1) "
                "AND ($2::text IS NULL OR requested_by = $2) ORDER BY requested_at DESC LIMIT $3",
                status,
                requested_by,
                limit,
            )
        return [_cr_dict(r) for r in records]

    async def review_change_request(
        self, cr_id: str, *, reviewer: str, approve: bool, comment: str | None
    ) -> dict[str, Any]:
        async with self.pool.acquire() as conn, conn.transaction():
            await self._expire_old(conn)
            cr = await conn.fetchrow("SELECT * FROM change_requests WHERE id = $1 FOR UPDATE", cr_id)
            if cr is None:
                raise AppError(ErrorCode.NOT_FOUND, f"Change request {cr_id} does not exist.")
            if cr["status"] != "pending":
                raise AppError(ErrorCode.CONFLICT, f"Change request {cr_id} has the status '{cr['status']}'.")
            if cr["requested_by"] == reviewer:
                raise AppError(
                    ErrorCode.PERMISSION_DENIED,
                    "Four-eyes rule: an agent cannot review its own change request.",
                    hint="Ask a different agent with the role 'approver'.",
                )
            status, result = "rejected", None
            if approve:
                status, result = await self._apply(conn, cr)
            record = await conn.fetchrow(
                "UPDATE change_requests SET status = $2, reviewed_by = $3, reviewed_at = now(), "
                "review_comment = $4, result = $5 WHERE id = $1 RETURNING *",
                cr_id,
                status,
                reviewer,
                comment,
                result,
            )
        metrics.CHANGE_REQUESTS.labels(status).inc()
        return _cr_dict(record)

    async def _apply(self, conn: asyncpg.Connection, cr: asyncpg.Record) -> tuple[str, dict[str, Any]]:
        operation, payload, passenger_id = cr["operation"], cr["payload"], cr["passenger_id"]
        if operation == "insert":
            cols = [c for c in WRITABLE_COLUMNS if c in payload]
            placeholders = ", ".join(f"${i}" for i in range(1, len(cols) + 1))
            new_id = await conn.fetchval(
                # cols is a subset of the constant WRITABLE_COLUMNS; all values are bound parameters.
                f"INSERT INTO passengers ({', '.join(cols)}) VALUES ({placeholders}) RETURNING passenger_id",  # nosec B608
                *[payload[c] for c in cols],
            )
            return "applied", {"passenger_id": new_id}

        current = await self._current_row(conn, passenger_id, lock=True)
        if current != cr["before"]:
            return "conflict", {
                "message": "The row changed after the proposal. Make a new change request.",
                "current": current,
            }
        if operation == "update":
            cols = [c for c in WRITABLE_COLUMNS if c in payload]
            assignments = ", ".join(f"{c} = ${i}" for i, c in enumerate(cols, start=2))
            await conn.execute(
                # assignments use only names from WRITABLE_COLUMNS; all values are bound parameters.
                f"UPDATE passengers SET {assignments} WHERE passenger_id = $1",  # nosec B608
                passenger_id,
                *[payload[c] for c in cols],
            )
        else:
            await conn.execute("DELETE FROM passengers WHERE passenger_id = $1", passenger_id)
        return "applied", {"passenger_id": passenger_id}


def _to_json_number(value: Any) -> Any:
    # PostgreSQL AVG() returns NUMERIC (Decimal). JSON needs a float.
    from decimal import Decimal

    return float(value) if isinstance(value, Decimal) else value


def _cr_dict(record: asyncpg.Record) -> dict[str, Any]:
    return {k: _iso(v) for k, v in dict(record).items()}


def _read_reference_rows(reference_db: Path) -> list[tuple[Any, ...]]:
    conn = sqlite3.connect(f"file:{reference_db}?mode=ro&immutable=1", uri=True)
    try:
        conn.execute(REFERENCE_VIEW_SQL)
        cols = ", ".join(["passenger_id", *WRITABLE_COLUMNS])
        # cols is built from the constant WRITABLE_COLUMNS.
        sql = f"SELECT {cols} FROM passengers ORDER BY passenger_id"  # nosec B608
        return [tuple(r) for r in conn.execute(sql)]
    finally:
        conn.close()
